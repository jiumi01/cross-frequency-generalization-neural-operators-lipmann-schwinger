"""Emit gen_si_refs.tex: the SI float numbers, keyed by their SI \\label.

Why this exists
---------------
The supplementary material is a separate LaTeX document, so \\ref cannot reach
it from the main text.  The prose therefore quoted its floats by hand
("Supplementary Table~12", "Supplementary Figure~S3").  Those literals are
positional: they are correct for one particular order of the SI and silently
wrong for any other.  That is not hypothetical -- inserting one figure in the
SI shifted every figure after it by one, and the main text went on citing the
old numbers while `check_si_refs.py` (which only knew about tables) reported a
clean bill of health.

The fix is to make the number symbolic.  The key is the SI float's own
\\label, so a renamed label fails loudly instead of renumbering a sentence:

    main text:   Supplementary Table~\\siTab{tab:si_born}
    emitted:     \\expandafter\\def\\csname sitab@tab:si_born\\endcsname{3}

The label is used raw as the \\csname body rather than being mangled into a
control word.  TeX ends a control word at the first non-letter, so a label such
as `tab:si_c1` would define `\\SITabC1` as `\\SITabC` and print the wrong number
without any error -- the macro-name trap already recorded for the number macros.

Numbering is the SI's own source order, which is the same order LaTeX counts;
`check_si_refs.py` cross-checks that against the numbers LaTeX actually wrote
into SI_main.aux, so a parser bug here cannot pass unnoticed.

Usage:  python code/gen_si_labels.py [--root DIR]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))

HEADER = (
    "% Auto-generated by code/gen_si_labels.py -- do not edit.\n"
    "% Key is the SI float's own \\label; see the gate check_si_refs.py.\n"
    "\\newcommand{\\siTab}[1]{\\ifcsname sitab@#1\\endcsname"
    "\\csname sitab@#1\\endcsname\\else\\textbf{??}\\fi}\n"
    "% The {} after \\endcsname is load-bearing: a control word swallows every\n"
    "% following letter, so \\endcsnameS would be read as the undefined control\n"
    "% sequence \\endcsnameS.  That is the mirror of the usual control-word trap\n"
    "% (a digit inside a name truncates it); both produce a wrong number with no\n"
    "% diagnostic, so the file states it here rather than in a commit message.\n"
    "\\newcommand{\\siFig}[1]{\\ifcsname sifig@#1\\endcsname{}S"
    "\\csname sifig@#1\\endcsname\\else\\textbf{??}\\fi}\n"
)


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def strip_comments(src):
    """Drop %-comments, but keep escaped \\% intact."""
    out = []
    for line in src.split("\n"):
        k = 0
        while True:
            j = line.find("%", k)
            if j < 0:
                out.append(line)
                break
            # count preceding backslashes
            b = 0
            p = j - 1
            while p >= 0 and line[p] == "\\":
                b += 1
                p -= 1
            if b % 2 == 1:          # escaped percent, keep scanning
                k = j + 1
                continue
            out.append(line[:j])
            break
    return "\n".join(out)


def inline_inputs(src, base, seen=None):
    """Replace every \\input{name} by the file's contents, recursively."""
    seen = seen or set()
    while True:
        m = re.search(r"\\input\{([^}]+)\}", src)
        if not m:
            return src
        name = m.group(1).strip()
        if not name.endswith(".tex"):
            name += ".tex"
        path = os.path.join(base, name)
        if not os.path.exists(path):
            # Not an error here: only the SI's own inputs carry floats.  Leave
            # the token alone so the caller can see what was not resolved.
            return src
        if path in seen:
            return src
        seen.add(path)
        src = src[:m.start()] + read(path) + src[m.end():]


def enumerate_floats(src):
    """Return (tables, figures) as ordered lists of (number, label-or-None)."""
    def walk(env):
        out = []
        pat = r"\\begin\{%s\*?\}(.*?)\\end\{%s\*?\}" % (env, env)
        for k, m in enumerate(re.finditer(pat, src, re.S), 1):
            lab = re.search(r"\\label\{([^}]+)\}", m.group(1))
            out.append((k, lab.group(1) if lab else None))
        return out
    return walk("table"), walk("figure")


def build(root):
    si_dir = os.path.join(root, "submission", "paper_en")
    src = inline_inputs(strip_comments(read(os.path.join(si_dir, "SI_main.tex"))),
                        si_dir)
    tables, figures = enumerate_floats(src)
    lines = [HEADER]
    for kind, items in (("sitab", tables), ("sifig", figures)):
        for num, lab in items:
            if not lab:
                continue
            lines.append("\\expandafter\\def\\csname %s@%s\\endcsname{%d}\n"
                         % (kind, lab, num))
    return "".join(lines), tables, figures


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=ROOT)
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    text, tables, figures = build(root)
    unlabeled = [n for n, l in tables + figures if not l]
    for lang in ("en",):
        out = os.path.join(root, "paper", lang, "gen_si_refs.tex")
        if not os.path.isdir(os.path.dirname(out)):
            continue
        old = read(out) if os.path.exists(out) else None
        # Written unconditionally: the build stage refuses to compile when a
        # generated file is older than main.tex, and a no-op write would leave
        # the mtime behind every time the manuscript was copied but the SI was
        # not.  The content is idempotent, so this only ever refreshes mtime.
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        if old != text:
            print("[si-refs] wrote paper/%s/gen_si_refs.tex (%d tables, "
                  "%d figures)" % (lang, len(tables), len(figures)))
        else:
            print("[si-refs] paper/%s/gen_si_refs.tex up to date" % lang)
        if unlabeled:
            print("[si-refs] WARNING: %d float(s) without a label, not "
                  "addressable: %s" % (len(unlabeled), unlabeled))
    return 0


if __name__ == "__main__":
    sys.exit(main())
