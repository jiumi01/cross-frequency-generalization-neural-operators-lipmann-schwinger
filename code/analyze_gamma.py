# Loss-tangent robustness of the correction: verdict + LaTeX, from the g10 runs.
# Pre-registered reading (fixed before the numbers are inspected):
#   replicates  if the in-band-selected head's plateau is at least 2x below
#               the trained gamma=0.10 FNO's plateau (both at v_max=0.25);
#   conditional otherwise, and the scope sentence keeps one loss tangent.
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common as C  # noqa: E402

RES = C.RES
ho = json.load(open(os.path.join(RES, "anchor_higher_order_g10.json"),
                    encoding="utf-8"))
sel = json.load(open(os.path.join(RES, "anchor_order_selection_g10.json"),
                     encoding="utf-8"))
mt = json.load(open(os.path.join(RES, "major4_tables.json"), encoding="utf-8"))
g10 = [r for r in mt["gamma_table"] if abs(r["gamma"] - 0.10) < 1e-9][0]

arm = ho["arms"]["0.25"]
m2 = arm["orders"]["2"]
# selected depth: the in-band rule of anchor_order_selection
mrow = sel["arms"]["0.25"]
msel = mrow.get("M_sel") or mrow.get("selected")
head = arm["orders"][str(msel)]

trained_plat = g10["plateau"][0]
trained_in = g10["inband"][0]
gain = trained_plat / head["plateau"] if head["plateau"] > 0 else float("inf")
verdict = "robust" if gain >= 2.0 else "conditional"

out = dict(
    gamma=0.10, vmax=0.25, msel=msel,
    anchor_in=m2["in_band"], anchor_plat=m2["plateau"], anchor_r=m2["r"],
    head_in=head["in_band"], head_plat=head["plateau"], head_r=head["r"],
    trained_in=trained_in, trained_plat=trained_plat,
    gain=gain, verdict=verdict,
)
C.save_json(out, os.path.join(RES, "gamma_verdict.json"))

B = chr(92)
macros = [
    ("GamAnchorR", "%.2f" % m2["r"]),
    ("GamAnchorPlat", "%.3f" % m2["plateau"]),
    ("GamHeadR", "%.2f" % head["r"]),
    ("GamHeadPlat", "%.4f" % head["plateau"]),
    ("GamTrainPlat", "%.3f" % trained_plat),
    ("GamTrainIn", "%.3f" % trained_in),
    ("GamGain", "%.0f" % gain),
]
lines = ["% Auto-generated by code/analyze_gamma.py -- do not edit."]
for name, val in macros:
    lines.append(B + "newcommand{" + B + "%s}{%s}" % (name, val))
root = os.path.dirname(HERE)
io.open(os.path.join(root, "submission", "paper_en", "gen_gam.tex"), "w",
        encoding="utf-8", newline="").write("\n".join(lines) + "\n")

# SI table body: the g10 depth scan, one row per order that fitted
rows = []
for o in sorted((int(k) for k in arm["orders"])):
    d = arm["orders"][str(o)]
    if not d.get("fitted"):
        rows.append("%d & refused & & \\\\\n" % o)
        continue
    mark = "*" if o == msel else ""
    rows.append("%d & %s%.3f & %s%.3f & %.2f \\\\\n"
                % (o, mark, d["in_band"], mark, d["plateau"], d["r"]))
tab = (B + "begin{tabular}{lccc}\n" + B + "toprule\n"
       + "order $M$ & $\\varepsilon_{\\mathrm{in}}$ & plateau & $r_{1}$ \\\\\n"
       + B + "midrule\n" + "".join(rows) + B + "bottomrule\n"
       + B + "end{tabular}\n")
io.open(os.path.join(root, "submission", "paper_en", "gen_tab_gam.tex"),
        "w", encoding="utf-8", newline="").write(tab)

print("gamma=0.10  M_sel=%s  anchor(M=2) plat %.3f r=%.2f | head plat %.3f "
      "r=%.2f | trained plat %.3f | gain %.1fx | verdict: %s"
      % (msel, m2["plateau"], m2["r"], head["plateau"], head["r"],
         trained_plat, gain, verdict))
