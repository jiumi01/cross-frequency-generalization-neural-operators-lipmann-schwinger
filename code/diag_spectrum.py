"""Spectral-content diagnostic.

For every test frequency we measure which fraction of the solution energy lives
outside the band of Fourier modes a given neural operator can represent
(|xi| <= 2*pi*M in each dimension).  This is the mechanistic quantity behind the
frequency-generalisation cliff.
"""
import os
import sys
import argparse
import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C
import physics as P
import data as D

# The media are generated by ``torch.Generator``, and a CUDA generator produces
# a DIFFERENT stream from a CPU one, so ``device`` is not just a performance
# knob: it silently changes which media every mean in this file is taken over.
# The device used is written into the JSON (key ``device``) so a reader can tell
# which stream a number came from, and the default is CPU because the run is
# cheap there (~1 minute) and CPU is the only choice that reproduces on a
# machine without the same GPU.  Only the *draws* differ between devices; the
# distribution, and therefore every conclusion drawn from these means, does not.
DEV = os.environ.get("LS_SPECTRUM_DEV") or "cpu"
MODES = [2, 4, 6, 8, 10, 12, 16, 20, 24, 32]


def fkey(f):
    """String key for a test frequency.

    ``"%.1f"`` was used here originally and it collapsed the two densified
    band-edge points onto ``4.2`` and ``4.8`` -- the same rounding defect that
    reached Table 1 through the table generator, and just as invisible, because
    both the writer and every reader used the same format.  ``%g`` prints the
    frequency the grid actually carries.
    """
    return "f=%g" % f


def band_energy(psi, M, N):
    """Fraction of L2 energy with |mode index| > M in EITHER dimension."""
    F = torch.fft.fft2(psi.to(torch.complex128), norm="ortho")
    P2 = (F.real ** 2 + F.imag ** 2)
    idx = torch.fft.fftfreq(N, d=1.0 / N, device=psi.device)
    mx = idx.abs().view(-1, 1)
    my = idx.abs().view(1, -1)
    outside = (mx > M) | (my > M)
    tot = P2.reshape(P2.shape[0], -1).sum(dim=1)
    out = P2 * outside[None].to(P2.dtype)
    out = out.reshape(out.shape[0], -1).sum(dim=1)
    return (out / tot.clamp_min(1e-30)).cpu().numpy()


def main():
    ap = argparse.ArgumentParser()
    # ``--n`` is the NUMBER OF SAMPLES, not the grid size (the grid is C.N = 64
    # and is not a knob here).  It used to default to 64, which reads like the
    # grid and silently produced a ten-times under-sampled statistic: every
    # published mean in this file would then be a 64-sample estimate while the
    # prose describes "600 paired media".  That is invisible in the output --
    # a mean over 64 draws prints exactly like a mean over 600 -- so the default
    # is now the sample count the manuscript quotes, and it is echoed at start-up.
    ap.add_argument("--samples", "--n", dest="n", type=int, default=600,
                    help="number of samples per (v_max, f) cell; --n is accepted "
                         "as an alias but the long name is the honest one, because "
                         "the grid size is C.N and is not settable here")
    ap.add_argument("--out", default=os.path.join(C.RES, "spectrum.json"))
    a = ap.parse_args()
    if a.n < 200:
        raise SystemExit("refusing to run with n=%d: the manuscript quotes means "
                         "over hundreds of paired media and a silent 10x "
                         "under-sample is not detectable in the output" % a.n)
    print("[spectrum] %d samples per cell, %d cells, device=%s"
          % (a.n, len(C.VMAX_LIST) * len(C.F_TEST), DEV), flush=True)
    res = dict(n=a.n, device=DEV, modes=MODES, f=C.F_TEST,
               vmax_list=C.VMAX_LIST, data={})
    for vmax in C.VMAX_LIST:
        arm = {}
        for f in C.F_TEST:
            d = D.sample_batch(a.n, 60000 + C.VMAX_LIST.index(vmax), DEV,
                               vmax_lo=vmax, vmax_hi=vmax, f_fixed=f)
            psi = d["psi"]
            psi_inc = P.incident_plane_wave(C.N, d["k"], d["theta"], DEV)
            u = (psi.to(torch.complex128) - psi_inc)
            nrm_psi = torch.linalg.norm(psi.reshape(a.n, -1), dim=1).cpu().numpy()
            nrm_u = torch.linalg.norm(u.reshape(a.n, -1), dim=1).cpu().numpy()
            be_psi = {M: band_energy(psi, M, C.N) for M in MODES}
            be_u = {M: band_energy(u, M, C.N) for M in MODES}
            arm[fkey(f)] = dict(
                psi={str(M): float(np.mean(be_psi[M])) for M in MODES},
                # mean of the PER-SAMPLE sqrt(delta_M): this is exactly the
                # aggregate quantity that the band-limitation bound lower-bounds
                # (E[rel_err] >= E[sqrt(delta_M)]; Jensen makes sqrt(E[delta]) an
                # upper, not lower, proxy, so it must not be used for the bound).
                # NOTE it is a property of the DATA, not a bound on the models
                # benchmarked here: the theorem needs an M-band-limited output,
                # and every model returns psi_inc + u_theta with psi_inc supplied
                # in full (the FNO adds a pointwise branch on top).  Kept because
                # it is the difficulty scale the data present at budget M.
                psi_sqrt_mean={str(M): float(np.mean(np.sqrt(be_psi[M])))
                               for M in MODES},
                psi_q10={str(M): float(np.quantile(be_psi[M], 0.10))
                         for M in MODES},
                u={str(M): float(np.mean(be_u[M])) for M in MODES},
                u_sqrt_mean={str(M): float(np.mean(np.sqrt(be_u[M])))
                             for M in MODES},
                # The premise-appropriate reference scale.  For a predictor of
                # the form psi_inc + P_M u_theta the residual splits
                # orthogonally as (P_M u_theta - P_M u) + (P_M u - u), whose two
                # parts live in band and out of band respectively, so
                #   ||psi_hat - psi|| / ||psi|| >= ||(I - P_M) u|| / ||psi||
                # exactly.  This is the quantity the mode budget really
                # constrains -- unlike delta_M(psi), which the free psi_inc
                # already carries.
                u_out_rel={str(M): float(np.mean(np.sqrt(be_u[M]) * nrm_u / nrm_psi))
                           for M in MODES},
                u_frac=float(nrm_u.mean() / nrm_psi.mean()),
                # The trivial baseline the network gets for free: it returns
                # psi_inc + u_theta, so u_theta == 0 is a legitimate predictor
                # whose relative error is exactly ||u||/||psi||.  Averaged
                # per sample, because the mean of the ratio and the ratio of the
                # means are not the same number and the arm heights are what
                # this is used to compare against.
                triv=float(np.mean(nrm_u / nrm_psi)),
            )
        res["data"][str(vmax)] = arm
        print("vmax=%.2f done" % vmax)
    C.save_json(res, a.out)
    # console summary: fraction of |psi| energy outside mode M, vmax = 0.25
    print("\nvmax=0.25  outside-band energy fraction of psi")
    print("f     " + "".join("%8d" % M for M in MODES))
    for f in C.F_TEST:
        row = res["data"]["0.25"][fkey(f)]["psi"]
        print("%5.1f " % f + "".join("%8.4f" % row[str(M)] for M in MODES))
    print("\nvmax=0.25  premise-appropriate bound  E[||(I-P_M)u||/||psi||]")
    print("f     " + "".join("%8d" % M for M in MODES))
    for f in C.F_TEST:
        row = res["data"]["0.25"][fkey(f)]["u_out_rel"]
        print("%5.1f " % f + "".join("%8.4f" % row[str(M)] for M in MODES))


if __name__ == "__main__":
    main()
